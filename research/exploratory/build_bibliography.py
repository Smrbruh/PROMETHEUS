"""Rebuild the deduplicated bibliography from inspected-source ledgers.

Does not retrieve or independently verify sources. DOI/URL identity is used
for deduplication, with original IDs retained as aliases.
"""
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parents[1]


def normal(value):
    return str(value or '').strip().lower().removeprefix('https://doi.org/').rstrip('/')


def main():
    rows = []
    for path in sorted((ROOT/'sources').glob('*.json')):
        if path.name == 'bibliography_index.json':
            continue
        entries = json.loads(path.read_text(encoding='utf-8-sig'))
        for row in entries:
            row = dict(row)
            row['_ledger'] = path.name
            rows.append(row)
    groups = []
    for row in rows:
        match = next((g for g in groups if
                      (normal(row.get('doi')) and normal(row.get('doi')) == normal(g[0].get('doi')))
                      or normal(row['url']) in {normal(r['url']) for r in g}), None)
        if match is None:
            groups.append([row])
        else:
            match.append(row)
    lines = ['# Consolidated bibliography', '',
             'Research/access date: **2026-10-10**. Primary-source records inspected during Phase 0. '
             '“Verified” refers to the stated metadata/access and supported claim, not independent reproduction of the method. '
             'Abstract/preview-only records are explicitly labeled. No full-paper review is implied.', '',
             f'{len(rows)} source records consolidate into **{len(groups)} distinct DOI/URL records**. '
             'Aliases preserve the identifiers used throughout the documents. Different documentation pages and code-license files '
             'remain separate resources. A DOI may contain a different year from the journal issue.', '',
             'Generated by `python research/exploratory/build_bibliography.py`; '
             'machine-readable original annotations are retained under `sources/`.', '']
    index = []
    for group in groups:
        r = group[0]
        aliases = [x['id'] for x in group]
        authors = r['authors']
        if isinstance(authors, list):
            authors = '; '.join(authors)
        lines += [f"## {' / '.join(aliases)} — {r['title']}", '',
                  f"{authors} ({r['year']}). *{r['venue']}*. "
                  f"[Canonical source]({r['url']})." +
                  (f" DOI: [{r['doi']}](https://doi.org/{r['doi']})." if r.get('doi') else ''), '',
                  f"**Contribution:** {r['contribution']} "
                  f"**Supports:** {r['supported_claim']}", '',
                  f"**Access:** {r['access']} "
                  f"**Limits:** {r['limitations']}", '']
        alt = list(dict.fromkeys(x['url'] for x in group if x['url'] != r['url']))
        if alt:
            lines += ['Additional inspected location: '+', '.join(f'[source]({u})' for u in alt)+'.', '']
        index.append({'ids': aliases, 'doi': r.get('doi'), 'url': r['url'],
                      'title': r['title'], 'ledgers': [x['_ledger'] for x in group]})
    (ROOT/'REFERENCES.md').write_text('\n'.join(lines), encoding='utf-8')
    (ROOT/'sources'/'bibliography_index.json').write_text(
        json.dumps(index, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
    print(json.dumps({'source_records':len(rows), 'distinct_records':len(groups),
                      'aliases':[g['ids'] for g in index if len(g['ids'])>1]}, ensure_ascii=True))


if __name__ == '__main__':
    main()
